// Regex transformations applied before character replacement for Unicode -> Preeti
export const UNICODE_TO_PREETI_PRE_RULES: [RegExp, string][] = [
  // Short-i (ि) in Unicode comes after consonant/cluster, but in Preeti 'l' comes before
  [/((?:[^\u0900-\u097F]|[\u0915-\u0939]\u094D)*[\u0915-\u0939])\u093F/g, 'l$1'],
  // Reph (र्) in Unicode comes before consonant/cluster, but in Preeti '{' comes after
  [/\u0930\u094D((?:[^\u0900-\u097F]|[\u0915-\u0939]\u094D)*[\u0915-\u0939])/g, '$1{'],
];

